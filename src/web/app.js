// Draws what the API returns. It computes nothing: sums, carries and every
// wire value come from the backend (Yosys sim on the gate netlist).
"use strict";

const els = {
  cases: document.getElementById("cases"),
  readout: document.getElementById("readout"),
  drawing: document.getElementById("drawing"),
  error: document.getElementById("error"),
  counts: document.getElementById("counts"),
};

async function getJson(path) {
  const resp = await fetch(path);
  const body = await resp.json().catch(() => ({}));
  if (!resp.ok) {
    throw new Error(body.detail || `request failed: ${resp.status}`);
  }
  return body;
}

function showError(message) {
  // Clear any earlier result so a stale drawing never sits beside an error.
  els.drawing.replaceChildren();
  els.readout.replaceChildren();
  els.error.textContent = message;
  els.error.hidden = false;
}

function clearError() {
  els.error.hidden = true;
  els.error.textContent = "";
}

function row(term, value) {
  const dt = document.createElement("dt");
  dt.textContent = term;
  const dd = document.createElement("dd");
  dd.textContent = value;
  return [dt, dd];
}

async function showCase(caseId, button) {
  for (const b of els.cases.querySelectorAll("button")) {
    b.setAttribute("aria-pressed", String(b === button));
  }
  try {
    const view = await getJson(`/api/adder/${encodeURIComponent(caseId)}`);
    clearError();
    els.readout.replaceChildren(
      ...row("a", view.a),
      ...row("b", view.b),
      ...row("cin", String(view.cin)),
      ...row("sum", view.sum),
      ...row("cout", String(view.cout)),
      ...row("gates", String(view.gate_count)),
    );
    // The SVG is generated by our backend from the netlist (no user input).
    const doc = new DOMParser().parseFromString(view.svg, "image/svg+xml");
    els.drawing.replaceChildren(document.importNode(doc.documentElement, true));
    els.drawing.scrollLeft = els.drawing.scrollWidth;  // start at bit 0
  } catch (err) {
    showError(err.message);
  }
}

async function showCounts() {
  try {
    const report = await getJson("/api/gate-counts");
    const head = document.createElement("tr");
    for (const h of ["Part", "Module", "Gates"]) {
      const th = document.createElement("th");
      th.textContent = h;
      head.append(th);
    }
    const rows = report.summary.map((r) => {
      const tr = document.createElement("tr");
      for (const v of [r.label, r.module, String(r.total_gates)]) {
        const td = document.createElement("td");
        td.textContent = v;
        tr.append(td);
      }
      return tr;
    });
    els.counts.replaceChildren(head, ...rows);
  } catch (err) {
    els.counts.replaceChildren();
    showError(err.message);
  }
}

async function init() {
  try {
    const cases = await getJson("/api/adder");
    const buttons = cases.map((c) => {
      const b = document.createElement("button");
      b.type = "button";
      b.textContent = c.label;
      b.addEventListener("click", () => showCase(c.case_id, b));
      return b;
    });
    els.cases.replaceChildren(...buttons);
    if (cases.length > 0) {
      await showCase(cases[0].case_id, buttons[0]);
    }
  } catch (err) {
    showError(err.message);
  }
  await showCounts();
}

init();
